let currentBook = null;
let currentChapterIdx = 0;

window.openBook = (id) => {
    const book = LIBRARY_DATA.books.find(b => b.id === id);
    if (!book) return;
    
    currentBook = book;
    currentChapterIdx = 0;
    
    document.getElementById('reader-title').textContent = book.title;
    document.getElementById('reader-author').textContent = book.author;
    const pdfBtn = document.getElementById('reader-pdf-btn');
    const pdfFallbackLink = document.getElementById('reader-pdf-fallback-link');
    const tocToggleBtn = document.getElementById('reader-toggle-toc-btn');
    const textBtn = document.getElementById('reader-text-btn');
    const newTabBtn = document.getElementById('reader-newtab-btn');
    const pdfViewer = document.getElementById('reader-pdf-viewer');
    const readerBody = document.getElementById('reader-body-container');
    const readerPdf = document.getElementById('reader-pdf-container');
    const readerSidebar = document.getElementById('reader-sidebar');
    if (pdfBtn && pdfFallbackLink && tocToggleBtn && textBtn && pdfViewer && readerBody && readerPdf && readerSidebar && newTabBtn) {
        if (book.pdfUrl) {
            pdfBtn.href = book.pdfUrl;
            pdfBtn.setAttribute('download', '');
            pdfBtn.style.display = 'inline-flex';
            pdfFallbackLink.href = book.pdfUrl;
            pdfFallbackLink.setAttribute('download', '');
            newTabBtn.style.display = 'inline-flex';
            tocToggleBtn.style.display = 'inline-flex';
            textBtn.style.display = 'inline-flex';
            pdfViewer.data = book.pdfUrl;
            readerBody.style.display = 'none';
            readerPdf.style.display = 'block';
            readerSidebar.classList.add('collapsed');
        } else {
            pdfBtn.style.display = 'none';
            newTabBtn.style.display = 'none';
            tocToggleBtn.style.display = 'inline-flex';
            textBtn.style.display = 'none';
            readerBody.style.display = 'block';
            readerPdf.style.display = 'none';
            // Auto collapse sidebar on mobile
            if (window.innerWidth <= 768) {
                readerSidebar.classList.add('collapsed');
            } else {
                readerSidebar.classList.remove('collapsed');
            }
        }
    }
    
    // Build TOC
    const toc = document.getElementById('reader-toc');
    toc.innerHTML = book.chapters.map((ch, idx) => `
        <li style="margin-bottom: 10px;">
            <a href="#" onclick="window.loadChapter(${idx}); return false;" style="color:var(--text-main); text-decoration:none; display:block; padding:8px; border-radius:5px; transition:background 0.2s;" class="toc-link" id="toc-${idx}">
                ${ch.title}
            </a>
        </li>
    `).join('');
    
    window.loadChapter(0);
    if(window.openModal) window.openModal('book-reader-modal');
};

window.loadChapter = (idx) => {
    if (!currentBook || !currentBook.chapters[idx]) return;
    currentChapterIdx = idx;
    
    const ch = currentBook.chapters[idx];
    document.getElementById('reader-content').innerHTML = `
        <h2 style="color:var(--primary); border-bottom:1px solid #eee; padding-bottom:15px; margin-bottom:20px;">${ch.title}</h2>
        <div style="font-size: 1.15rem; line-height: 1.8;">
            ${ch.content}
        </div>
    `;
    
    // Auto collapse sidebar on mobile after selecting a chapter
    if (window.innerWidth <= 768) {
        document.getElementById('reader-sidebar').classList.add('collapsed');
    }
    
    document.getElementById('reader-progress').textContent = `Chapit ${idx + 1} / ${currentBook.chapters.length}`;
    
    // Highlight TOC
    document.querySelectorAll('.toc-link').forEach(l => {
        l.style.background = 'transparent';
        l.style.color = 'var(--text-main)';
        l.style.fontWeight = 'normal';
    });
    const activeToc = document.getElementById(`toc-${idx}`);
    if (activeToc) {
        activeToc.style.background = 'rgba(0, 168, 232, 0.1)';
        activeToc.style.color = 'var(--primary)';
        activeToc.style.fontWeight = 'bold';
    }
    
    // Buttons
    document.getElementById('reader-prev-btn').disabled = (idx === 0);
    document.getElementById('reader-next-btn').disabled = (idx === currentBook.chapters.length - 1);
};

window.prevChapter = () => { if (currentChapterIdx > 0) window.loadChapter(currentChapterIdx - 1); };
window.nextChapter = () => { if (currentBook && currentChapterIdx < currentBook.chapters.length - 1) window.loadChapter(currentChapterIdx + 1); };

